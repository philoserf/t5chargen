// schemaPath is the contract docs/PRD.md's JSON conventions require:
// "Full schema (with minimal and complete examples) lives in the tool
// repo, versioned by schema_version".
const (
	schemaPath      = docsPath + "character.schema.json"
	minimalExample  = docsPath + "character.minimal.json"
	completeExample = docsPath + "character.complete.json"
)

// TestEveryFixtureValidates verifies the schema describes what the engine
// actually writes. The fixtures are its output, byte for byte, across all
// thirteen careers and both deciders.
func TestEveryFixtureValidates(t *testing.T) {
	records, err := filepath.Glob(filepath.Join("..", "chargen", "testdata", "*.json"))
	if err != nil {
		t.Fatal(err)
	}

	if len(records) == 0 {
		t.Fatal("no fixtures found; this gate would be asserting nothing")
	}

	for _, record := range records {
		t.Run(filepath.Base(record), func(t *testing.T) {
			problems, err := validate(record)
			if err != nil {
				t.Fatal(err)
			}

			for _, problem := range problems {
				t.Error(problem)
			}
		})
	}
}

// TestExamplesValidate verifies the two examples the PRD asks the schema to
// ship with. The minimal one is the smallest record the schema admits; the
// complete one is a real generated record rather than a fabricated maximum,
// which is why the coverage of the schema's properties is checked
// separately rather than assumed of it.
func TestExamplesValidate(t *testing.T) {
	for _, example := range []string{minimalExample, completeExample} {
		t.Run(example, func(t *testing.T) {
			problems, err := validate(example)
			if err != nil {
				t.Fatal(err)
			}

			for _, problem := range problems {
				t.Error(problem)
			}
		})
	}
}

// completeExample is the fixture docs/character.complete.json is a copy
// of. The example has to be a record the engine really wrote, and the only
// way to keep it one is to say which.
const completeFixture = "career_scout.json"

// TestTheExamplesTrackTheEngine keeps the two shipped examples honest.
//
// The complete one is a copy of a golden fixture, and `task goldens`
// rewrites the fixture without touching the copy — a drifted copy would go
// on validating, so nothing else here would notice. The provenance strings
// are pinned the same way: an example advertising a schema_version the
// engine no longer stamps documents a contract that has moved.
func TestTheExamplesTrackTheEngine(t *testing.T) {
	fixture := filepath.Join("..", "chargen", "testdata", completeFixture)

	if canonical(t, completeExample) != canonical(t, fixture) {
		t.Errorf("the complete example is no longer %s; re-copy it, because task goldens does not", fixture)
	}

	// policy_version is deliberately absent: a record generated by
	// something other than the auto policy carries "none" (chargen's
	// provenance header), so it is not a constant the examples track.
	stamped := map[string]string{
		"schema_version": chargen.SchemaVersion,
		"ruleset":        chargen.Ruleset,
		"engine_version": chargen.EngineVersion,
	}

	for _, example := range []string{minimalExample, completeExample} {
		record := readRecord(t, example)

		for field, want := range stamped {
			if got, _ := record[field].(string); got != want {
				t.Errorf("%s carries %s %q; the engine stamps %q", example, field, got, want)
			}
		}
	}
}

// canonical re-encodes a JSON file with its keys sorted, so two files that
// differ only in whitespace compare equal. docs/*.json is prettier's and
// chargen/testdata/*.json is json.MarshalIndent's, so the two copies of
// the complete example are never byte-identical.
func canonical(t *testing.T, path string) string {
	t.Helper()

	data, err := os.ReadFile(filepath.Clean(path))
	if err != nil {
		t.Fatal(err)
	}

	var doc any
	if err = json.Unmarshal(data, &doc); err != nil {
		t.Fatal(err)
	}

	encoded, err := json.Marshal(doc)
	if err != nil {
		t.Fatal(err)
	}

	return string(encoded)
}

// TestTheMinimalExampleIsMinimal verifies the minimal example earns its
// name: removing any one of its top-level fields must break it. A minimal
// example carrying something optional would misdocument what a record
// needs.
func TestTheMinimalExampleIsMinimal(t *testing.T) {
	base := readRecord(t, minimalExample)

	for field := range base {
		record := readRecord(t, minimalExample)
		delete(record, field)

		if problems := checkRecord(t, record); len(problems) == 0 {
			t.Errorf("the minimal example still validates without %q, so %q is not required", field, field)
		}
	}
}

// readRecord loads a record as a plain document.
func readRecord(t *testing.T, path string) map[string]any {
	t.Helper()

	data, err := os.ReadFile(filepath.Clean(path))
	if err != nil {
		t.Fatal(err)
	}

	var record map[string]any
	if err := json.Unmarshal(data, &record); err != nil {
		t.Fatal(err)
	}

	return record
}

// checkRecord validates an in-memory record. It goes back through JSON
// first, so the validator meets the value space a file would give it.
func checkRecord(t *testing.T, record map[string]any) []string {
	t.Helper()

	encoded, err := json.Marshal(record)
	if err != nil {
		t.Fatal(err)
	}

	problems, err := validateJSON(encoded)
	if err != nil {
		t.Fatal(err)
	}

	return problems
}

// validate checks one document against the schema, returning its problems.
func validate(docPath string) ([]string, error) {
	data, err := os.ReadFile(filepath.Clean(docPath))
	if err != nil {
		return nil, fmt.Errorf("reading %s: %w", docPath, err)
	}

	return validateJSON(data)
}

// validateJSON checks one encoded document against the schema.
func validateJSON(data []byte) ([]string, error) {
	schema, err := compiledSchema()
	if err != nil {
		return nil, err
	}

	doc, err := jsonschema.UnmarshalJSON(bytes.NewReader(data))
	if err != nil {
		return nil, fmt.Errorf("parsing the record: %w", err)
	}

	// A validation failure is the answer, not an error: the problems are
	// what the caller asked for.
	if invalid := schema.Validate(doc); invalid != nil {
		return []string{invalid.Error()}, nil //nolint:nilerr // a failed validation is the result, not an error
	}

	return nil, nil
}

// compiledSchema compiles docs/character.schema.json once.
//
// The validator is imported, test-scoped. It was once written here to keep
// the repository dependency-free, and by the time it was re-priced it was
// ~650 lines: the checker, and the meta-tests a hand-written checker needs
// so that a bug in it cannot pass everything. It never reaches the binary:
// depguard admits it in _test.go files only.
var compiledSchema = sync.OnceValues(func() (*jsonschema.Schema, error) {
	data, err := os.ReadFile(filepath.Clean(schemaPath))
	if err != nil {
		return nil, fmt.Errorf("reading the schema: %w", err)
	}

	doc, err := jsonschema.UnmarshalJSON(bytes.NewReader(data))
	if err != nil {
		return nil, fmt.Errorf("parsing the schema: %w", err)
	}

	compiler := jsonschema.NewCompiler()
	if addErr := compiler.AddResource(schemaURL, doc); addErr != nil {
		return nil, fmt.Errorf("loading the schema: %w", addErr)
	}

	schema, err := compiler.Compile(schemaURL)
	if err != nil {
		return nil, fmt.Errorf("compiling the schema: %w", err)
	}

	return schema, nil
})

// schemaURL is the schema's own $id, the name the compiler knows it by.
const schemaURL = "https://philoserf.github.io/t5chargen/character.schema.json"

// TestEverySchemaPropertyIsExercised is the dead-data gate applied to the
// schema. A property nothing ever produces is either a field the engine no
// longer writes or a shape nobody has checked, and both are worth knowing
// about; the schema is a claim about real records, not a wish list.
//
// The complete example is a real generated record rather than a fabricated
// maximum, so it does not reach every optional field on its own. What is
// unreached is listed here with a reason, the same bargain the chart-data
// gate strikes.
func TestEverySchemaPropertyIsExercised(t *testing.T) {
	records, err := filepath.Glob(filepath.Join("..", "chargen", "testdata", "*.json"))
	if err != nil {
		t.Fatal(err)
	}

	if len(records) == 0 {
		t.Fatal("no fixtures found; this gate would be asserting nothing")
	}

	seen := keysAcross(t, append(records, minimalExample, completeExample))

	for _, property := range schemaProperties(t) {
		if seen[property] || unexercised[property] != "" {
			continue
		}

		t.Errorf("the schema describes %q and no fixture or example carries it; "+
			"produce one, or say why not in unexercised", property)
	}

	for property, why := range unexercised {
		if seen[property] {
			t.Errorf("%q is exercised now (%s); remove it from unexercised", property, why)
		}
	}
}

// unexercised are schema properties no fixture or example carries, and
// why. Every entry is a rule the engine implements down a path the pinned
// seeds do not reach — not a field that does nothing.
var unexercised = map[string]string{
	"deep_space":       "chart B's cell 6 6 (I-97); no fixture rolls its homeworld, and none is assigned deep space",
	"rolled_homeworld": "--homeworld random; every fixture takes the assigned world, so the input is false and omitted",
	"homeworld_assigned": "--homeworld; no fixture names one, so step B offers chart B's list " +
		"and the input is false and omitted",
	"service":      "the Service Academy's service; the auto policy never selects the Academy (POLICY.md)",
	"exiled":       "chart 11's Noble exile; the pinned Noble seed is not exiled",
	"prison_years": "a Rogue serving a sentence; the pinned Rogue seed serves none",
}

// keysAcross gathers every property name appearing anywhere in any of the
// documents.
func keysAcross(t *testing.T, paths []string) map[string]bool {
	t.Helper()

	seen := map[string]bool{}

	for _, path := range paths {
		data, err := os.ReadFile(filepath.Clean(path))
		if err != nil {
			t.Fatal(err)
		}

		var doc any
		if err := json.Unmarshal(data, &doc); err != nil {
			t.Fatal(err)
		}

		collectKeys(doc, seen)
	}

	return seen
}

// collectKeys gathers every property name appearing anywhere in a document.
func collectKeys(doc any, seen map[string]bool) {
	switch value := doc.(type) {
	case map[string]any:
		for key, child := range value {
			seen[key] = true

			collectKeys(child, seen)
		}
	case []any:
		for _, child := range value {
			collectKeys(child, seen)
		}
	}
}

// schemaProperties lists every property name the schema describes.
func schemaProperties(t *testing.T) []string {
	t.Helper()

	data, err := os.ReadFile(filepath.Clean(schemaPath))
	if err != nil {
		t.Fatal(err)
	}

	var schema map[string]any
	if err := json.Unmarshal(data, &schema); err != nil {
		t.Fatal(err)
	}

	seen := map[string]bool{}
	defs, _ := schema["$defs"].(map[string]any)

	for _, def := range defs {
		object, _ := def.(map[string]any)

		properties, _ := object["properties"].(map[string]any)
		for name := range properties {
			seen[name] = true
		}
	}

	names := make([]string, 0, len(seen))
	for name := range seen {
		names = append(names, name)
	}

	sort.Strings(names)

	return names
}

