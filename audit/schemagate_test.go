// TestEveryConsequenceKindIsAccountedFor verifies the schema's vocabulary
// against what the engine can actually emit. A kind in the enum that
// nothing produces is either a rule nobody exercises or one that has
// quietly stopped working, and the difference is worth writing down.
func TestEveryConsequenceKindIsAccountedFor(t *testing.T) {
	declared := scan(t, isGoSource, regexp.MustCompile(`ConsequenceKind = "([a-z_0-9]+)"`))
	if len(declared) == 0 {
		t.Fatal("no consequence kinds found; this gate would be asserting nothing")
	}

	for _, kind := range declared {
		_, emitted := consequenceFields[kind]
		if emitted == (unemittedKinds[kind] != "") {
			if emitted {
				t.Errorf("%q is emitted by a fixture; remove it from unemittedKinds", kind)
			} else {
				t.Errorf("%q is declared and no fixture emits it; produce one, or say why not in unemittedKinds", kind)
			}
		}
	}

	assertVocabulary(t, "consequenceEvent", "kind", declared)
}

// vocabularies are the schema's closed lists and the Go constants each one
// transcribes. A value the engine can write and the schema does not hold
// makes the schema wrong about a real record, and nothing else here would
// notice until some fixture happened to carry it.
// The package each is declared in matters: "Kind" is a type name three
// packages use, so a pattern loose enough to find benefit.Kind finds
// skill.Kind as well and reports five vocabulary values that belong to
// another list entirely.
var vocabularies = []struct {
	def, property, dir, pattern string
}{
	{def: "consequenceEvent", property: "kind", dir: "chargen", pattern: `ConsequenceKind = "([a-z_0-9]+)"`},
	{def: "event", property: "kind", dir: "chargen", pattern: `EventKind\s+= "([a-z]+)"`},
	{def: "choiceEvent", property: "decider", dir: "chargen", pattern: `DeciderKind = "([a-z]+)"`},
	{def: "benefitRecord", property: "kind", dir: "benefit", pattern: `\bKind = "([a-z_]+)"`},
}

// TestEverySchemaVocabularyMatchesTheEngine checks each closed list in the
// schema against the constants it transcribes, in both directions.
//
// The consequence kinds had this and the other three did not, which meant a
// new benefit kind would have gone unnoticed until a fixture happened to
// carry one — and the fixtures reach six of the nineteen.
func TestEverySchemaVocabularyMatchesTheEngine(t *testing.T) {
	for _, v := range vocabularies {
		t.Run(v.def+"."+v.property, func(t *testing.T) {
			declared := scan(t, inPackage(v.dir), regexp.MustCompile(v.pattern))
			if len(declared) == 0 {
				t.Fatalf("no constants matched %s; this gate would be asserting nothing", v.pattern)
			}

			assertVocabulary(t, v.def, v.property, declared)
		})
	}
}

// assertVocabulary compares one schema enum with the constants behind it.
func assertVocabulary(t *testing.T, def, property string, declared []string) {
	t.Helper()

	inSchema := map[string]bool{}
	for _, value := range schemaEnum(t, def, property) {
		inSchema[value] = true
	}

	inGo := map[string]bool{}

	for _, value := range declared {
		inGo[value] = true

		if !inSchema[value] {
			t.Errorf("the engine writes %q and %s.%s does not hold it", value, def, property)
		}
	}

	for value := range inSchema {
		if !inGo[value] {
			t.Errorf("%s.%s holds %q and no constant declares it", def, property, value)
		}
	}
}

// schemaEnum reads one property's enum out of the schema.
func schemaEnum(t *testing.T, def, property string) []string {
	t.Helper()

	data, err := os.ReadFile(filepath.Clean(schemaPath))
	if err != nil {
		t.Fatal(err)
	}

	var schema struct {
		Defs map[string]struct {
			Properties map[string]struct {
				Enum []string `json:"enum"`
			} `json:"properties"`
		} `json:"$defs"`
	}

	if err := json.Unmarshal(data, &schema); err != nil {
		t.Fatal(err)
	}

	return schema.Defs[def].Properties[property].Enum
}
